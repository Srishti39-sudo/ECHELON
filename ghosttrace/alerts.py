@lru_cache(maxsize=16)
def _kb_text(kb_dir: str, doc: str) -> str:
    try:
        return (Path(kb_dir) / doc).read_text(encoding="utf-8")
    except OSError:
        return ""


def _front_matter(text: str) -> dict[str, str]:
    m = re.match(r"^---\n(.*?)\n---\n", text, flags=re.S)
    out = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                out[k.strip()] = v.strip()
    return out


def _squash(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().lower()


def kb_dir_path(kb_dir: Any = None) -> str:
    p = Path(kb_dir or cfg.KB_DIR)
    return str(p if p.is_absolute() else REPO_ROOT / p)


def name_in_corpus(name: str, doc: str, kb_dir: Any = None) -> bool:
    return _squash(name) in _squash(_kb_text(kb_dir_path(kb_dir), doc))


def situations_for(target: dict[str, Any]) -> list[str]:
    cls = target.get("object_class")
    out = []
    if class_family(cls) == cfg.ACTIVE_GEAR_FAMILY:
        out.append("fisheries")
    if class_family(cls) == "unknown":
        out.append("unidentified_object")
    if any(class_matches(cls, k) for k in ("drum", "container", "barrel", "cylinder")):
        out += ["unknown_contents", "possible_pollution"]
    habitat = target.get("habitat") or {}
    drift = target.get("drift") or {}
    near = False
    if habitat.get("available", True):
        if habitat.get("inside"):
            near = True
        for n in habitat.get("nearest") or []:
            if isinstance(n.get("distance_m"), (int, float)) and n["distance_m"] <= cfg.NEAR_HABITAT_M:
                near = True
        if isinstance(habitat.get("score"), (int, float)) and habitat["score"] >= cfg.NEAR_HABITAT_SCORE:
            near = True
    if drift.get("available", True):
        for i in drift.get("impacts") or []:
            kind = f"{i.get('kind')} {i.get('name')}".lower().replace(" ", "-")
            if (i.get("probability") or 0) > 0 and any(k in kind for k in cfg.SENSITIVE_IMPACT_KINDS):
                near = True
    # A seabed net the "if refloated" scenario carries into a protected area is
    # a net that area's manager should hear about, even though the scenario
    # never raises priority. Held to a higher bar than the forecast.
    for i in _scenario_impacts(target):
        kind = f"{i.get('kind')} {i.get('name')}".lower().replace(" ", "-")
        if (i.get("probability") or 0) >= cfg.SCENARIO_NOTIFY_PROBABILITY and \
                any(k in kind for k in cfg.SENSITIVE_IMPACT_KINDS):
            near = True
    if near:
        out.append("protected_habitat")
    level = str(((target.get("people") or {}).get("propeller_hazard") or {}).get("level") or "").lower()
    if level in cfg.PROPELLER_HAZARD_LEVELS:
        out.append("navigation_hazard")
    return out


def _habitat_names(target: dict[str, Any]) -> str:
    """Every habitat name the target is inside, near, or forecast to reach, lowercased.

    Used only to pick which location-scoped office an alert names. A target
    with no habitat context matches none of them and the alert says the
    authority is not in the corpus, rather than defaulting to some park.
    """
    habitat = target.get("habitat") or {}
    drift = target.get("drift") or {}
    names: list[str] = []
    if habitat.get("available", True):
        for item in habitat.get("inside") or []:
            names.append(str(item.get("name") if isinstance(item, dict) else item))
        names += [str(n.get("name") or "") for n in habitat.get("nearest") or []]
    if drift.get("available", True):
        names += [str(i.get("name") or "") for i in drift.get("impacts") or []
                  if (i.get("probability") or 0) > 0]
    names += [str(i.get("name") or "") for i in _scenario_impacts(target)
              if (i.get("probability") or 0) >= cfg.SCENARIO_NOTIFY_PROBABILITY]
    return " | ".join(names).lower()


def _scenario_impacts(target: dict[str, Any]) -> list[dict[str, Any]]:
    """Impacts of the "if refloated" drift scenario, or none."""
    scenario = (target.get("drift_scenarios") or {}).get("if_refloated") or {}
    if scenario.get("available", True) is False:
        return []
    return [i for i in scenario.get("impacts") or [] if isinstance(i, dict)]


def authorities_for(target: dict[str, Any], kb_dir: Any = None
                    ) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """(authorities, citations). Names only from the corpus; gaps stated."""
    kbd = kb_dir_path(kb_dir)
    authorities: list[dict[str, Any]] = []
    citations: list[dict[str, Any]] = []
    places = _habitat_names(target)
    for situation in situations_for(target):
        found = False
        for entry in AUTHORITY_REGISTRY.get(situation, []):
            text = _kb_text(kbd, entry["doc"])
            if not name_in_corpus(entry["name"], entry["doc"], kbd):
                continue
            match = entry.get("habitat_match")
            if match and not any(m in places for m in match):
                continue
            fm = _front_matter(text)
            authorities.append({
                "name": entry["name"], "role": entry["role"], "situation": situation,
                "contact_basis": (f"named in kb/{entry['doc']} (section '{entry['section']}'); "
                                  "the corpus gives no phone number, email or address for it, so "
                                  "none is given here"),
            })
            citations.append({"doc": f"kb/{entry['doc']}", "section": entry["section"],
                              "title": fm.get("title"), "source_url": fm.get("source_url"),
                              "status": fm.get("status")})
            found = True
        if not found:
            role = MISSING_ROLE.get(situation) or f"authority for situation '{situation}'"
            authorities.append({
                "name": cfg.NOT_IN_CORPUS, "role": role, "situation": situation,
                "contact_basis": ("no document in kb/ names this authority; add a verified source "
                                  "to the corpus rather than guessing a contact"),
            })
    if authorities:
        fm = _front_matter(_kb_text(kbd, "reporting-authorities-india.md"))
        if fm:
            citations.append({**REPORT_FIELDS_CITATION, "title": fm.get("title"),
                              "source_url": fm.get("source_url"), "status": fm.get("status")})
    # De-duplicate citations, keep order.
    seen, uniq = set(), []
    for c in citations:
        key = (c["doc"], c["section"])
        if key not in seen:
            seen.add(key)
            uniq.append(c)
    return authorities, uniq


