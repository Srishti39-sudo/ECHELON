def _fmt_pos(t: dict[str, Any]) -> str:
    if t.get("latitude") is None or t.get("longitude") is None:
        return "position unavailable"
    return f"{float(t['latitude']):.5f}, {float(t['longitude']):.5f}"


def _source_name(src: Any) -> str:
    if isinstance(src, dict):
        return str(src.get("name") or "source not named")
    return str(src) if src else "source not stated"


def _lines(t: dict[str, Any], survey_id: str, demo: bool, synthetic: bool) -> list[str]:
    cls = t.get("object_class")
    lines = []
    if demo or synthetic:
        lines.append("SYNTHETIC / DEMO DATA - this is not a real detection and must not be sent.")
    lines.append("AUTOMATED DETECTION - VERIFY BEFORE ACTION.")
    pct = t.get("confidence_pct")
    lines.append(f"What: side-scan sonar contact classified '{cls}'"
                 + (f", confidence {pct:.0f}% ({t.get('confidence_basis')})." if isinstance(pct, (int, float))
                    else ", confidence not recorded."))
    if t.get("latitude") is None:
        lines.append("Where: position unavailable (survey not georeferenced).")
    else:
        lines.append(f"Where: {_fmt_pos(t)} (decimal degrees, WGS84 as recorded by the survey "
                     "navigation; accuracy not estimated).")
    dims = t.get("dimensions")
    if isinstance(dims, dict) and dims.get("length_m") is not None:
        parts = [f"{dims.get(k):.1f} m" for k in ("length_m", "width_m", "height_m")
                 if isinstance(dims.get(k), (int, float))]
        lines.append("Size: " + " x ".join(parts) + " (length x width x height as measured).")
    else:
        lines.append("Size: not measured.")

    a = t.get("activity") or {}
    if a.get("available"):
        ev = a.get("evidence") or {}
        lines.append(f"Water-column activity: {a.get('level')} (score {a.get('score')}; "
                     f"{ev.get('echo_clusters_near')} echo clusters within {ev.get('window_m')} m "
                     f"vs {ev.get('background_clusters_per_window')} per control window; may be "
                     "fish, bubbles or sediment - not proof of entanglement).")
    else:
        lines.append(f"Water-column activity: not measured ({a.get('reason', 'unavailable')}).")

    h = t.get("habitat") or {}
    if h.get("available", True) and ("nearest" in h or "inside" in h):
        inside = [i.get("name") if isinstance(i, dict) else str(i) for i in h.get("inside") or []]
        if inside:
            lines.append("Habitat: inside " + ", ".join(str(x) for x in inside) + ".")
        nearest = sorted((n for n in h.get("nearest") or [] if isinstance(n.get("distance_m"), (int, float))),
                         key=lambda n: n["distance_m"])
        if nearest:
            n = nearest[0]
            lines.append(f"Nearest habitat: {n.get('name')} ({n.get('kind')}) at "
                         f"{n['distance_m'] / 1000:.2f} km"
                         + (f", bearing {n['bearing_deg']:.0f} deg" if isinstance(n.get("bearing_deg"), (int, float)) else "")
                         + f" (source: {_source_name(n.get('source'))}).")
        elif not inside:
            lines.append("Habitat: no mapped habitat layer near the target.")
    else:
        lines.append(f"Habitat: unavailable ({h.get('reason', 'no habitat stage')}).")

    d = t.get("drift") or {}
    if d.get("available", True) and isinstance(d.get("impacts"), list):
        mode = d.get("mode") or d.get("requested_mode")
        horizon = d.get("horizon_hours")
        impacts = sorted(d["impacts"], key=lambda i: -(i.get("probability") or 0))
        if impacts:
            i = impacts[0]
            arrival = i.get("first_arrival_hours")
            lines.append(f"Drift forecast ({mode}, {horizon} h): {100 * (i.get('probability') or 0):.0f}% "
                         f"chance of reaching {i.get('name')} ({i.get('kind')})"
                         + (f", first arrival about {arrival:.0f} h" if isinstance(arrival, (int, float)) else "")
                         + ".")
        else:
            lines.append(f"Drift forecast ({mode}, {horizon} h): no mapped habitat reached.")
        if isinstance(d.get("stranding_probability"), (int, float)):
            lines.append(f"Stranding probability: {100 * d['stranding_probability']:.0f}%.")
    else:
        lines.append(f"Drift forecast: unavailable ({d.get('reason', 'no drift stage')}).")

    scenario_impacts = sorted(_scenario_impacts(t), key=lambda i: -(i.get("probability") or 0))
    if scenario_impacts:
        i = scenario_impacts[0]
        arrival = i.get("first_arrival_hours")
        lines.append(f"Scenario, not a forecast -- if this net is lifted off the seabed: "
                     f"{100 * (i.get('probability') or 0):.0f}% chance of reaching {i.get('name')}"
                     + (f", first arrival about {arrival:.0f} h" if isinstance(arrival, (int, float)) else "")
                     + ".")

    p = t.get("people") or {}
    if p.get("available", True) and p.get("propeller_hazard"):
        ph = p["propeller_hazard"]
        reasons = "; ".join(str(r) for r in (ph.get("reasons") or [])[:3])
        lines.append(f"Propeller hazard: {ph.get('level')}" + (f" - {reasons}" if reasons else "") + ".")
        brief = p.get("diver_brief")
        if isinstance(brief, dict):
            text = brief.get("summary") or "; ".join(
                f"{k}: {v}" for k, v in brief.items() if isinstance(v, (str, int, float)))[:400]
            if text:
                lines.append(f"Diver notes: {text}.")
        elif isinstance(brief, str):
            lines.append(f"Diver notes: {brief}.")
    else:
        lines.append(f"Propeller / diver hazard: unavailable ({p.get('reason', 'no safety stage')}).")

    c = t.get("change") or {}
    if c.get("status"):
        moved = ""
        if c.get("moved_m") is not None:
            moved = (f", displacement {c['moved_m']} m (within positional uncertainty, not claimed as "
                     "movement)" if c["status"] == "persistent" else f", moved {c['moved_m']} m")
        if c.get("previous_survey_id"):
            moved += f" (compared with survey {c['previous_survey_id']})"
        lines.append(f"Change since previous survey: {c['status']}{moved}.")
    pr = t.get("priority") or {}
    if pr:
        lines.append(f"GhostTrace priority: {pr.get('tier')} (score {pr.get('score')}, rank "
                     f"{pr.get('rank')}; heuristic).")
    lines.append(f"Survey: {survey_id}. Detection: {t.get('detection_id')}.")
    lines.append("Still to be completed by the operator before sending (per kb/reporting-"
                 "authorities-india.md, 'What a report carries'): time of detection in UTC, "
                 "position datum and accuracy estimate, water and object depth, sensor settings, "
                 "vessel identity, operator, and the vessel's intentions.")
    return lines


def template_alert(target: dict[str, Any], *, survey_id: str, demo: bool = False,
                   synthetic: bool = False, kb_dir: Any = None) -> dict[str, Any]:
    authorities, citations = authorities_for(target, kb_dir)
    lines = _lines(target, survey_id, demo, synthetic)
    if authorities:
        lines.append("Report to:")
        for a in authorities:
            lines.append(f"  - {a['name']}: {a['role']}.")
    lines.append(cfg.ALERT_DISCLAIMER)
    tier = (target.get("priority") or {}).get("tier") or "unranked"
    prefix = "[SYNTHETIC] " if (demo or synthetic) else ""
    subject = (f"{prefix}GhostTrace {tier}: suspected {target.get('object_class')} at "
               f"{_fmt_pos(target)} (survey {survey_id})")
    return {"authorities": authorities, "subject": subject, "draft_text": "\n".join(lines),
            "generated_by": "template", "citations": citations,
            "basis": ("deterministic template from this target's GhostTrace fields; authorities "
                      "only where kb/ names them for the situation")}


def _assistant_answer(message: str, detection: dict[str, Any]) -> dict[str, Any]:
    import sys
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    from rag_assistant.chat import answer  # noqa: WPS433 (optional dependency)
    return answer(message, detection=detection)


def draft_alert(target: dict[str, Any], *, survey_id: str, demo: bool = False,
                synthetic: bool = False, kb_dir: Any = None,
                use_assistant: bool | None = None, assistant_fn=None) -> dict[str, Any]:
    """Alert block for one target. Template unless the assistant is enabled and succeeds."""
    alert = template_alert(target, survey_id=survey_id, demo=demo, synthetic=synthetic, kb_dir=kb_dir)
    use = cfg.USE_ASSISTANT if use_assistant is None else use_assistant
    if not use:
        return alert
    fn = assistant_fn or _assistant_answer
    message = ("Using only the sources, draft a short report to the responsible authority about "
               "this side-scan sonar contact. Do not add any contact details that are not in the "
               "sources. Facts:\n" + alert["draft_text"])
    detection = {"object_class": target.get("object_class"),
                 "confidence": (target.get("confidence_pct") or 0) / 100.0}
    pool = concurrent.futures.ThreadPoolExecutor(max_workers=1)
    try:
        future = pool.submit(fn, message, detection)
        result = future.result(timeout=cfg.ASSISTANT_TIMEOUT_S)
    except concurrent.futures.TimeoutError:
        alert["basis"] += f"; assistant timed out after {cfg.ASSISTANT_TIMEOUT_S:g} s, template used"
        return alert
    except BaseException as exc:  # SystemExit from rag.py included
        alert["basis"] += f"; assistant failed ({type(exc).__name__}: {str(exc)[:160]}), template used"
        return alert
    finally:
        pool.shutdown(wait=False)
    text = (result or {}).get("answer")
    if not text or result.get("refusal") or not result.get("grounded", False):
        alert["basis"] += "; assistant answer was a refusal or not grounded, template used"
        return alert
    sources = [{k: s.get(k) for k in ("n", "title", "section", "doc_id", "authority", "status", "path")}
               for s in result.get("sources") or []]
    alert.update({
        "draft_text": text.rstrip() + "\n\n" + cfg.ALERT_DISCLAIMER,
        "generated_by": "assistant",
        "citations": alert["citations"] + [{"assistant_source": s} for s in sources],
        "basis": ("grounded assistant (rag_assistant.chat.answer) given the template facts; the authority "
                  "list is from the deterministic corpus check, not from the model"),
    })
    return alert
