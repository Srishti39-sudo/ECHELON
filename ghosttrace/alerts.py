"""Who should be told, and what should the message say?

A detection nobody reports rescues nothing. This module drafts one alert per
target: a subject, a plain-text body a survey lead can paste into an email or
a radio log, the authorities the message is for, and the corpus citations for
every authority it names.

THE ONE RULE: NO INVENTED CONTACTS
    An authority is named only when a document in kb/ names it for that
    situation, and the name is checked against the document text at run time
    (whitespace-normalised, case-insensitive). If the kb changes and the name
    disappears, the entry degrades to "authority not in corpus" by itself.
    No phone number, email address or URL that is not in the corpus is ever
    written. Where the corpus is silent - and for ghost gear it largely is -
    the alert says so explicitly, because an honest gap sends the operator to
    find the right office, while a plausible invented one sends the report to
    the wrong desk.

WHAT THE CORPUS ACTUALLY COVERS (kb/, as of this writing)
    * kb/reporting-authorities-india.md names the Indian Coast Guard Maritime
      Rescue Coordination Centre as the reporting channel for a discharge or
      probable discharge of oil / hazardous and noxious substances. It is
      offered ONLY for drums and containers (possible contents), and its role
      text says it is not the channel for the gear itself.
    * The same document says a hazard to navigation is broadcast by "the
      authority", and kb/unidentified-object-protocol.md says to call
      "emergency services" for an object of unknown nature - but no Indian
      office for navigational warnings, fisheries, marine protected areas or
      wildlife is named anywhere. Those situations get "authority not in
      corpus" with the role that is missing.

GENERATED BY
    "template" (default, offline, deterministic) or "assistant" when
    GHOSTTRACE_USE_ASSISTANT=1: the template facts are sent through the
    existing grounded assistant (rag_assistant.chat.answer) with a timeout. Any
    failure, refusal or ungrounded answer falls back to the template and the
    reason is recorded in `basis`. The authority list always comes from the
    deterministic corpus check, never from the model.
"""

