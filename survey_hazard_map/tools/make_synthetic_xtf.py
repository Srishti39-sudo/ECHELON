def _track(pings: int, dt: float):
    """Towfish state per ping in local east/north metres. All numpy arrays."""
    import numpy as np

    t = np.arange(pings) * dt
    duration = max(t[-1], dt)
    speed = 2.0 + 0.45 * np.sin(2 * np.pi * t / 90.0) + 0.2 * np.sin(2 * np.pi * t / 23.0)
    # Roughly east-west along the island chain, gently curving.
    heading = (95.0 + 12.0 * np.sin(np.pi * t / duration)
               - 5.0 * np.sin(3 * np.pi * t / duration)) % 360
    rad = np.radians(heading)
    east = np.concatenate([[0.0], np.cumsum(speed[:-1] * dt * np.sin(rad[:-1]))])
    north = np.concatenate([[0.0], np.cumsum(speed[:-1] * dt * np.cos(rad[:-1]))])
    along = np.concatenate([[0.0], np.cumsum(speed[:-1] * dt)])
    heave = 0.08 * np.sin(2 * np.pi * t / 6.5)
    pitch = 0.8 * np.sin(2 * np.pi * t / 9.0)
    roll = 1.2 * np.sin(2 * np.pi * t / 7.0)
    # Water depth 8..18 m, deepest over both nets so the control comparison is
    # made in the same depth of water.
    depth = 13.0 + 5.0 * np.cos(2 * np.pi * (t / duration - 0.74) / 0.56)
    return {"t": t, "speed": speed, "heading": heading, "east": east, "north": north,
            "along": along, "heave": heave, "pitch": pitch, "roll": roll, "depth": depth}


def _altitude(track: dict):
    """Sensor height above the seabed. Heave positive = sensor up."""
    return track["depth"] - (SENSOR_DEPTH_M - track["heave"])


def _target_en(track: dict, ping: int, cross: float) -> tuple[float, float]:
    """East/north of a point `cross` metres to starboard of the towfish at `ping`."""
    hr = math.radians(float(track["heading"][ping]))
    return (float(track["east"][ping]) + cross * math.cos(hr),
            float(track["north"][ping]) - cross * math.sin(hr))


def _layout(pings: int, scenario: str = "baseline", track: dict | None = None) -> dict:
    """Where defects and targets go, as fractions of the line so --pings scales it."""
    def at(fraction: float) -> int:
        return int(round(fraction * pings))

    layout = _baseline_layout(pings, at)
    if scenario == "baseline":
        return layout
    if scenario != "repeat":
        raise ValueError(f"unknown scenario {scenario!r}; choose from {SCENARIOS}")
    if track is None:
        raise ValueError("the repeat scenario needs the track to place the moved net")
    targets = []
    changes = []
    for entry in layout["targets"]:
        tid, cls, ping, cross, kind, params = entry
        if tid == "T7":
            changes.append({"id": "T7", "change": "removed",
                            "note": "not on the seabed in the repeat survey"})
            continue
        if tid == "T5":
            old = _target_en(track, ping, cross)
            # The abeam ping (searched backwards along the line) whose new
            # position is closest to REPEAT_MOVE_M from the old one.
            best = min(range(max(0, ping - 600), ping),
                       key=lambda q: abs(math.dist(old, _target_en(track, q, REPEAT_T5_CROSS_M))
                                         - REPEAT_MOVE_M))
            new = _target_en(track, best, REPEAT_T5_CROSS_M)
            from_lat, from_lon = offset_latlon(ORIGIN_LAT, ORIGIN_LON, old[0], old[1])
            changes.append({"id": "T5", "change": "moved",
                            "displacement_m": round(math.dist(old, new), 2),
                            "from_latitude": round(from_lat, 8), "from_longitude": round(from_lon, 8),
                            "from_ping_abeam": int(ping), "from_cross_track_m": cross,
                            "to_ping_abeam": int(best), "to_cross_track_m": REPEAT_T5_CROSS_M})
            entry = (tid, cls, best, REPEAT_T5_CROSS_M, kind, params)
        targets.append(entry)
    targets.append(("T8", "net", at(0.44), -12.0, "net",
                    {"length": 7.0, "width": 5.0, "orient": 35.0,
                     "note": "faint draped mesh, no aggregation: a net that arrived since the "
                             "baseline line"}))
    changes.append({"id": "T8", "change": "new", "note": "not present in the baseline line"})
    layout["targets"] = targets
    layout["scenario_changes"] = changes
    layout["control_net"] = "T8"
    return layout


