#!/usr/bin/env python3
"""Write a SYNTHETIC side-scan XTF file with known ground truth.

    python3 tools/make_synthetic_xtf.py                       # samples/synthetic_xtf/
    python3 tools/make_synthetic_xtf.py --out /tmp/x --pings 1600 --seed 57
    python3 tools/make_synthetic_xtf.py --start-time 2026-09-06T04:30:00Z
    python3 tools/make_synthetic_xtf.py --scenario repeat --name SYNTHETIC_mannar_line02 \
        --start-time 2026-09-09T04:30:00Z                     # the same line, re-surveyed

EVERYTHING THIS WRITES IS SYNTHETIC. No sonar was deployed and no object or
fish exists. The XTF file header's NoteString, an XTF notes packet at the start
of the file, and the ground-truth JSON all say so, and sonar_ingest reads that
marking and carries `"synthetic": true` into every strip it produces. The point
of the file is to exercise the real ingest path -- a genuine XTF parsed by
pyxtf, with real ping headers -- against positions that are known exactly,
which no public survey offers.

The line runs roughly east-west in the Gulf of Mannar, near the Marine National
Park island chain (about 9.12 N, 79.05 E), in 8 to 18 m of water. The place is
chosen because ghost nets and reef fish are the survey problem there. Nothing
about the seabed below is a model of the real one.

WHY IT IS BUILT FROM GEOMETRY, NOT PAINTED
    A painted strip tests nothing about georeferencing: the pixel positions
    would be whatever the painter chose. Here a towfish is flown along a
    curving track, each ping's samples are generated by casting the beam's
    slant ranges onto a height field of the seabed, and ground truth is the
    objects' true positions on that seabed. So a target only appears where
    slant-range geometry, heading and navigation put it, and ingesting the file
    back has to undo all three to find it again.

THE PHYSICS, AND ITS LIMITS
    slant sample k      r = k * SlantRange / NumSamples
    ground point        g = sqrt(r^2 - a^2) across-track from the fish, a = altitude
    return strength     reflectivity * sin(grazing angle + facet slope)^1.2
    acoustic shadow     a point is dark when a nearer, taller point already
                        blocks the ray (running minimum of depression angle)
    speckle             multiplicative Rayleigh, unit mean
    roll                port/starboard gain imbalance
    pitch               energy loss and a fore/aft footprint shift r*sin(pitch)
    heave               moves the sensor up and down, changing its altitude
    water depth         8..18 m; the fish tows at a fixed depth, so the seabed
                        shoaling under it changes the altitude

    Not modelled: layover (object heights do not shorten their slant range),
    multipath, refraction, beam pattern beyond a smooth gain, yaw/crab, fish
    shadows on the seabed.

INJECTED DEFECTS (all recorded in the truth file)
    attitude excursion  a segment of heavy pitch, roll and heave
    time-gap dropout    pings never written; the clock jumps, the fish moves on
    empty pings         pings written with all-zero samples

TARGETS (all recorded in the truth file with true lat/lon and size)
    cylinder x2         2.0 m x 0.5 m, metal, strong highlight and shadow
    pipe                long, thin, oblique to the track
    shipwreck           24 m x 7 m hull in shallow water
    net x2              draped, irregular, faint mesh
    rock cluster        natural boulders: false-positive bait, not man-made
    sand ripples        seabed texture over part of the line

FISH IN THE WATER COLUMN
    A fish is a point scatterer at a fixed depth. A ping sees it when it lies
    inside the beam's fore/aft footprint on that channel's side, and its echo
    lands at its true slant range: in the water column, before the first bottom
    return, when it is close enough across-track, and over the seabed returns
    otherwise.

    net T5      dense schools above and around it, on its side, spread about
                30 m along-track: the signature of a net still ghost-fishing.
                "fish_aggregation": true.
    net T7      the control: same side, similar cross-track distance, similar
                water depth, and no aggregation. "fish_aggregation": false.
    elsewhere   sparse single fish on both sides, as background. None is placed
                inside T5's aggregation window, so the aggregation is exactly
                what the truth file lists.

SCENARIOS (--scenario)
    baseline    the line as described above (the default; unchanged output).
    repeat      the SAME track flown again later (use --start-time), for
                testing change tracking across surveys:
                  T5  MOVED about REPEAT_MOVE_M (40 m) along and across the
                      track, still ghost-fishing (the aggregation moves with it)
                  T7  REMOVED: not on the seabed any more
                  T8  NEW net elsewhere inside the swath, no aggregation
                  every other target is where it was
                Seabed shapes come from the same seed, so unchanged targets
                look the same; speckle and background fish come from a
                different stream, as a second recording would. The truth file
                records every change under "scenario_changes".
"""

